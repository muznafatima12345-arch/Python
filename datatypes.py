#Type casting
# String to Integer
age = "19"
age = int(age)
print(age, type(age))

# Integer to Float
percentage = "80.0"
percentage = float(percentage)
print(percentage, type(percentage))

# Float to Integer
fee = 8000.00
fee = int(fee)
print(fee, type(fee))

# Number to string 
marks = 100
marks = str(marks)
print(marks, type(marks))

#List to tuple
numbers = [10,20,30]
numbers_tuple = tuple(numbers)
print(numbers_tuple, type(numbers_tuple))

#Tuple to List
numbers_list = list(numbers)
print(numbers_list, type(numbers_list))





