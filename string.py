text = "Muznab"
print(text)
print(len(text))

#Uppercase
print(text.upper())

#Lowercase
print(text.lower())

#Capitalize
print(text.capitalize())

#Replace
print(text.replace("muznab", "muzna"))

# Indexing
print(text[0])
print(text[1])
print(text[-1])

# Slicing
print(text[0:3])
print(text[2:5])
print(text[2:])
print(text[::-1])

