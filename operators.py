#Arithmetic Operators
a = 10
b = 3
print(a + b)
print(a - b)
print(a * b)
print(a / b)
print(a // b)
print(a % b)

#Comparison Operators
print(a == b)
print(a != b)
print(a > b)
print(a < b)
print(a >= b)
print(a <= b)


#Assignment Operators
x = 5
print(x)
x += 1
print(x)
x -= 2
print(x)
x *= 2
print(x)
x /= 2
print(x)


#Logical Operators
a = 10
b = 5

print(a > 5 and b < 10)
print(a > 15 or b < 10)
print(not(a > 5))





